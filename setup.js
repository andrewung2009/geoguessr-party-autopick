'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const readline = require('readline/promises');

const ROOT = __dirname;
const ENV_PATH = path.join(ROOT, '.env');
const MAPS_PATH = path.join(ROOT, 'config', 'maps.json');

function parseEnv(text) {
  const result = {};
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq < 0) continue;
    result[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim();
  }
  return result;
}

function readExistingEnv() {
  try {
    return parseEnv(fs.readFileSync(ENV_PATH, 'utf8'));
  } catch {
    return {};
  }
}

function writeEnv(values) {
  const content = `# Generated by setup.js. You can edit this file, but do not share it.
DISCORD_TOKEN=${values.DISCORD_TOKEN}
ALLOWED_DISCORD_USER_IDS=${values.ALLOWED_DISCORD_USER_IDS}
BRIDGE_SECRET=${values.BRIDGE_SECRET}
BRIDGE_PORT=${values.BRIDGE_PORT}
`;
  fs.writeFileSync(ENV_PATH, content, 'utf8');
}

function readMaps() {
  try {
    return JSON.parse(fs.readFileSync(MAPS_PATH, 'utf8'));
  } catch {
    return null;
  }
}

function writeMaps(data) {
  fs.writeFileSync(MAPS_PATH, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
}

function mapsNeedingNames(data) {
  return (data.maps || []).filter(
    (map) => !String(map.mapId || '').trim() && !String(map.geoguessrName || '').trim()
  );
}

async function main() {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  const ask = (question) => rl.question(question);

  console.log('');
  console.log('==============================================');
  console.log(' GeoGuessr Party Autopick - setup');
  console.log('==============================================');
  console.log('');
  console.log('This wizard fills in .env for you.');
  console.log('Press Enter to keep the value shown in [brackets].');
  console.log('');

  const existing = readExistingEnv();

  const token = (
    await ask(`Discord bot token [${existing.DISCORD_TOKEN ? 'already set' : 'not set'}]: `)
  ).trim();
  const allowed = (
    await ask(
      `Your Discord user ID(s), comma separated (numeric is best) [${existing.ALLOWED_DISCORD_USER_IDS || 'not set'}]: `
    )
  ).trim();
  const port = (
    await ask(`Bridge port [${existing.BRIDGE_PORT || '8787'}]: `)
  ).trim();

  let secret = existing.BRIDGE_SECRET && !existing.BRIDGE_SECRET.includes('paste_')
    ? existing.BRIDGE_SECRET
    : crypto.randomBytes(24).toString('hex');

  const values = {
    DISCORD_TOKEN: token || existing.DISCORD_TOKEN || '',
    ALLOWED_DISCORD_USER_IDS: allowed || existing.ALLOWED_DISCORD_USER_IDS || '',
    BRIDGE_SECRET: secret,
    BRIDGE_PORT: port || existing.BRIDGE_PORT || '8787'
  };

  writeEnv(values);

  console.log('');
  console.log('Saved .env');

  const usernameEntries = values.ALLOWED_DISCORD_USER_IDS.split(',')
    .map((entry) => entry.trim())
    .filter((entry) => entry && !/^\d+$/.test(entry));
  if (usernameEntries.length > 0) {
    console.log('');
    console.log(
      `Note: ${usernameEntries.join(', ')} looks like a username, not a numeric user ID.`
    );
    console.log('It will work, but a numeric ID is safer and will not change if the username changes.');
  }

  console.log('');
  console.log('Bridge secret (paste this into the Tampermonkey setup panel):');
  console.log(`  ${values.BRIDGE_SECRET}`);
  console.log('');

  const mapsData = readMaps();
  if (!mapsData) {
    console.log('Could not read config/maps.json. Skipping map check.');
  } else {
    const missing = mapsNeedingNames(mapsData);
    if (missing.length === 0) {
      console.log('All maps have a geoguessrName or mapId. Nothing to fill in.');
    } else {
      console.log('Some maps still need a full GeoGuessr name.');
      console.log('You can type them now, or leave blank and edit config/maps.json later.');
      console.log('');

      let changed = false;
      for (const map of missing) {
        const answer = (
          await ask(`Full GeoGuessr map name for "${map.shorthand}" (blank to skip): `)
        ).trim();
        if (answer) {
          map.geoguessrName = answer;
          map.note = '';
          changed = true;
        }
      }

      if (changed) {
        writeMaps(mapsData);
        console.log('');
        console.log('Updated config/maps.json.');
      }
    }
  }

  console.log('');
  console.log('Next steps:');
  console.log('');
  console.log('  1. npm install');
  console.log('  2. npm run register');
  console.log('  3. Open the install link printed by step 2 and add the app to your account.');
  console.log('  4. Install userscript/geoguessr-party-autopick.user.js in Tampermonkey.');
  console.log('  5. npm start');
  console.log('  6. Open the GeoGuessr party lobby and click the overlay to paste the bridge secret.');
  console.log('');
  console.log('See FILL-ME-IN.md for the short checklist.');
  console.log('');

  rl.close();
}

main().catch((error) => {
  console.error('');
  console.error('Setup failed:', error.message);
  process.exit(1);
});
